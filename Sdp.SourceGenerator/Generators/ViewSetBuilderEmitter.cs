using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Sdp.SourceGenerator.Generators;

internal static class ViewSetBuilderEmitter
{
    public static string Emit(ViewSetAnalysis.Builder analysis)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        var viewSet = analysis.Symbol;
        var scope = EmitHelper.OpenNamespaceAndContainingTypes(sb, viewSet);
        var indent = scope.Indent;

        var viewSetFullyQualifiedName = viewSet.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var tableSetFullyQualifiedName = analysis.TableSetSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        sb.Append(indent).Append("partial ").Append(EmitHelper.GetTypeKeyword(viewSet)).Append(' ')
            .AppendLine(EmitHelper.EscapeIdentifier(viewSet.Name));
        sb.Append(indent).AppendLine("{");

        var memberIndent = indent + "    ";
        switch (analysis)
        {
            case ViewSetAnalysis.ViewSetBuilder viewSetBuilder:
                EmitViewSetBuilder(sb, viewSetBuilder, viewSetFullyQualifiedName, tableSetFullyQualifiedName, memberIndent);
                break;
            case ViewSetAnalysis.DeferredErrorBuilder deferredErrorBuilder:
                EmitDeferredErrorBuilder(sb, deferredErrorBuilder, viewSetFullyQualifiedName, tableSetFullyQualifiedName, memberIndent);
                break;
            case ViewSetAnalysis.NotSupportedBuilder:
                EmitNotSupportedBuilder(sb, viewSetFullyQualifiedName, tableSetFullyQualifiedName, memberIndent);
                break;
            default:
                throw new InvalidOperationException(FormattableString.Invariant(
                    $"Unhandled builder analysis '{analysis.GetType().Name}'."));
        }

        sb.Append(indent).AppendLine("}");
        EmitHelper.CloseContainingTypes(sb, scope);

        return sb.ToString();
    }

    private static void EmitViewSetBuilder(
        StringBuilder sb,
        ViewSetAnalysis.ViewSetBuilder analysis,
        string viewSetFullyQualifiedName,
        string tableSetFullyQualifiedName,
        string indent)
    {
        EmitBuildSignature(sb, viewSetFullyQualifiedName, tableSetFullyQualifiedName, indent);
        sb.Append(indent).AppendLine("{");
        sb.Append(indent).AppendLine("    var __errors = new global::System.Collections.Generic.List<global::System.Exception>();");
        sb.AppendLine();

        for (var viewIndex = 0; viewIndex < analysis.Views.Length; viewIndex++)
        {
            var view = analysis.Views[viewIndex];
            var viewFullyQualifiedName = view.ViewSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            sb.Append(indent).Append("    ").Append(viewFullyQualifiedName).Append(" __v").Append(viewIndex).AppendLine(" = null!;");
            sb.Append(indent).AppendLine("    try");
            sb.Append(indent).AppendLine("    {");
            sb.Append(indent).Append("        __v").Append(viewIndex)
                .Append(" = global::Sdp.View.ViewSetBuildHelper.Build<")
                .Append(viewFullyQualifiedName).Append(", ").Append(tableSetFullyQualifiedName).Append(">(tableSet, ")
                .Append(Literal(view.ParameterName)).Append(", ")
                .Append(viewFullyQualifiedName).AppendLine(".BuildView, logger);");
            sb.Append(indent).AppendLine("    }");
            sb.Append(indent).AppendLine("    catch (global::System.Exception ex)");
            sb.Append(indent).AppendLine("    {");
            sb.Append(indent).AppendLine("        __errors.Add(ex);");
            sb.Append(indent).AppendLine("    }");
            sb.AppendLine();
        }

        sb.Append(indent).AppendLine("    if (__errors.Count > 0)");
        sb.Append(indent).AppendLine("    {");
        sb.Append(indent).AppendLine("        throw new global::System.AggregateException(global::Sdp.View.ViewSetBuildHelper.ViewsFailedToBuildMessage, __errors);");
        sb.Append(indent).AppendLine("    }");
        sb.AppendLine();

        sb.Append(indent).Append("    return new ").Append(viewSetFullyQualifiedName).Append("(");
        for (var viewIndex = 0; viewIndex < analysis.Views.Length; viewIndex++)
        {
            if (viewIndex > 0)
            {
                sb.Append(", ");
            }

            sb.Append("__v").Append(viewIndex);
        }

        sb.AppendLine(");");
        sb.Append(indent).AppendLine("}");
    }

    private static void EmitDeferredErrorBuilder(
        StringBuilder sb,
        ViewSetAnalysis.DeferredErrorBuilder analysis,
        string viewSetFullyQualifiedName,
        string tableSetFullyQualifiedName,
        string indent)
    {
        // 같은 메시지에 들어가는 View 쪽 TableSet(ViewTableSetName)과 컴파일 타임 진단(SDP0304/0308)이
        // 모두 네임스페이스 포함 표기를 쓰므로 동일하게 맞춘다.
        var tableSetName = analysis.TableSetSymbol.ToDisplayString();

        EmitBuildSignature(sb, viewSetFullyQualifiedName, tableSetFullyQualifiedName, indent);
        sb.Append(indent).AppendLine("{");
        sb.Append(indent).AppendLine("    var __errors = new global::System.Collections.Generic.List<global::System.Exception>();");

        foreach (var view in analysis.Views)
        {
            if (view.IsNullable)
            {
                sb.Append(indent).Append("    __errors.Add(global::Sdp.View.ViewSetBuildHelper.NullableViewMemberError(")
                    .Append(Literal(view.ParameterName)).Append(", ").Append(Literal(view.TypeName)).AppendLine("));");
            }

            if (!view.TargetsStaticDataManagerTableSet)
            {
                sb.Append(indent).Append("    __errors.Add(global::Sdp.View.ViewSetBuildHelper.ViewTargetsDifferentTableSetError(")
                    .Append(Literal(view.TypeName)).Append(", ").Append(Literal(view.ViewTableSetName ?? string.Empty))
                    .Append(", ").Append(Literal(tableSetName)).AppendLine("));");
            }
            else if (!view.HasValidCtor)
            {
                sb.Append(indent).Append("    __errors.Add(global::Sdp.View.ViewSetBuildHelper.ViewConstructorNotFoundError(")
                    .Append(Literal(view.TypeName)).Append(", ").Append(Literal(tableSetName)).AppendLine("));");
            }

            if (!view.IsPartial)
            {
                sb.Append(indent).Append("    __errors.Add(global::Sdp.View.ViewSetBuildHelper.ViewNotPartialError(")
                    .Append(Literal(view.TypeName)).AppendLine("));");
            }

            if (!view.ContainingTypesPartial)
            {
                sb.Append(indent).Append("    __errors.Add(global::Sdp.View.ViewSetBuildHelper.ViewContainingTypeNotPartialError(")
                    .Append(Literal(view.TypeName)).AppendLine("));");
            }
        }

        sb.Append(indent).AppendLine("    throw new global::System.AggregateException(global::Sdp.View.ViewSetBuildHelper.ViewsFailedToBuildMessage, __errors);");
        sb.Append(indent).AppendLine("}");
    }

    private static void EmitNotSupportedBuilder(
        StringBuilder sb,
        string viewSetFullyQualifiedName,
        string tableSetFullyQualifiedName,
        string indent)
    {
        EmitBuildSignature(sb, viewSetFullyQualifiedName, tableSetFullyQualifiedName, indent);
        sb.Append(indent).AppendLine("{");
        sb.Append(indent).Append("    throw global::Sdp.View.ViewSetBuildHelper.CannotEmitError(\"")
            .Append(viewSetFullyQualifiedName).AppendLine("\");");
        sb.Append(indent).AppendLine("}");
    }

    private static void EmitBuildSignature(
        StringBuilder sb,
        string viewSetFullyQualifiedName,
        string tableSetFullyQualifiedName,
        string indent)
    {
        sb.Append(indent).Append("internal static ").Append(viewSetFullyQualifiedName).AppendLine(" Build(");
        sb.Append(indent).Append("    ").Append(tableSetFullyQualifiedName).AppendLine(" tableSet,");
        sb.Append(indent).AppendLine("    global::Microsoft.Extensions.Logging.ILogger logger)");
    }

    private static string Literal(string value)
    {
        return SymbolDisplay.FormatLiteral(value, quote: true);
    }
}
