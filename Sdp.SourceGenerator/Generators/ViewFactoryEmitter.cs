using System.Text;
using Microsoft.CodeAnalysis;

namespace Sdp.SourceGenerator.Generators;

internal static class ViewFactoryEmitter
{
    public static string Emit(StaticDataViewAnalysis.Factory analysis)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        var scope = EmitHelper.OpenNamespaceAndContainingTypes(sb, analysis.Symbol);
        var indent = scope.Indent;

        var viewFullyQualifiedName = analysis.Symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var tableSetFullyQualifiedName = analysis.TableSetSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        sb.Append(indent).Append("partial class ").AppendLine(EmitHelper.EscapeIdentifier(analysis.Symbol.Name));
        sb.Append(indent).AppendLine("{");

        sb.Append(indent).Append("    internal static ").Append(viewFullyQualifiedName)
            .Append(" BuildView(").Append(tableSetFullyQualifiedName).AppendLine(" tableSet)");
        switch (analysis)
        {
            case StaticDataViewAnalysis.ViewFactory:
                sb.Append(indent).AppendLine("    {");
                sb.Append(indent).Append("        var __view = new ").Append(viewFullyQualifiedName).AppendLine("(tableSet);");
                sb.Append(indent).AppendLine("        __view.Validate();");
                sb.Append(indent).AppendLine("        return __view;");
                sb.Append(indent).AppendLine("    }");
                break;
            case StaticDataViewAnalysis.NotSupportedFactory:
                sb.Append(indent).Append("        => throw global::Sdp.View.ViewSetBuildHelper.CannotEmitError(\"")
                    .Append(viewFullyQualifiedName).AppendLine("\");");
                break;
            default:
                throw new InvalidOperationException(FormattableString.Invariant(
                    $"Unhandled factory analysis '{analysis.GetType().Name}'."));
        }

        sb.Append(indent).AppendLine("}");
        EmitHelper.CloseContainingTypes(sb, scope);

        return sb.ToString();
    }
}
