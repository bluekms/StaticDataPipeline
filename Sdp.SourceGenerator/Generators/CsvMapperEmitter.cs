using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Sdp.SourceGenerator.Generators;

internal static partial class CsvMapperEmitter
{
    public static string Emit(RecordAnalysis.Mapper analysis)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        var scope = EmitHelper.OpenNamespaceAndContainingTypes(sb, analysis.Symbol);
        var indent = scope.Indent;

        var recordKeyword = EmitHelper.GetTypeKeyword(analysis.Symbol);
        sb.Append(indent).Append("partial ").Append(recordKeyword).Append(' ')
            .AppendLine(EmitHelper.EscapeIdentifier(analysis.TypeName));
        sb.Append(indent).AppendLine("{");

        var memberIndent = indent + "    ";
        switch (analysis)
        {
            case RecordAnalysis.CsvMapper csvMapper:
            {
                var nestedTokens = BuildNestedTokenMap(csvMapper.Parameters);
                EmitCsvMapper(sb, csvMapper, memberIndent, nestedTokens);
                EmitEmptyRowCheck(sb, csvMapper.Parameters, memberIndent);
                EmitHelpers(sb, csvMapper.Parameters, memberIndent, nestedTokens);
                break;
            }

            case RecordAnalysis.NotSupportedMapper:
                EmitNotSupportedMapper(sb, analysis, memberIndent);
                break;
            default:
                throw new InvalidOperationException(FormattableString.Invariant(
                    $"Unhandled mapper analysis '{analysis.GetType().Name}'."));
        }

        sb.Append(indent).AppendLine("}");
        EmitHelper.CloseContainingTypes(sb, scope);

        return sb.ToString();
    }

    private static void EmitNotSupportedMapper(StringBuilder sb, RecordAnalysis.Mapper analysis, string indent)
    {
        sb.Append(indent).Append("internal static ").Append(analysis.FullyQualifiedTypeName).AppendLine(" MapFromCsvRow(");
        sb.Append(indent).AppendLine("    global::Sdp.Csv.CsvHeaderIndex headers,");
        sb.Append(indent).AppendLine("    string[] values)");
        sb.Append(indent).AppendLine("{");
        sb.Append(indent).Append("    throw global::Sdp.Csv.CsvMapperHelper.MapperNotSupported(")
            .Append(SymbolDisplay.FormatLiteral(analysis.FullyQualifiedTypeName, quote: true)).AppendLine(");");
        sb.Append(indent).AppendLine("}");
        sb.AppendLine();
        sb.Append(indent).AppendLine("internal static bool IsEmptyCsvRow(global::Sdp.Csv.CsvHeaderIndex headers, string[] values)");
        sb.Append(indent).AppendLine("{");
        sb.Append(indent).AppendLine("    return false;");
        sb.Append(indent).AppendLine("}");
    }

    private static void EmitCsvMapper(
        StringBuilder sb,
        RecordAnalysis.CsvMapper analysis,
        string indent,
        Dictionary<INamedTypeSymbol, string> nestedTokens)
    {
        sb.Append(indent).Append("internal static ").Append(analysis.FullyQualifiedTypeName).AppendLine(" MapFromCsvRow(");
        sb.Append(indent).AppendLine("    global::Sdp.Csv.CsvHeaderIndex headers,");
        sb.Append(indent).AppendLine("    string[] values)");
        sb.Append(indent).AppendLine("{");
        sb.Append(indent).Append("    return new ").Append(analysis.FullyQualifiedTypeName).AppendLine("(");

        for (var i = 0; i < analysis.Parameters.Length; i++)
        {
            var param = analysis.Parameters[i];
            sb.Append(indent).Append("        ");
            sb.Append(EmitHelper.EscapeIdentifier(param.Name)).Append(": ");
            sb.Append(EmitConversion(param, basePathVar: null, ownerToken: string.Empty, nestedTokens));

            if (i < analysis.Parameters.Length - 1)
            {
                sb.Append(',');
            }

            sb.AppendLine();
        }

        sb.Append(indent).AppendLine("    );");
        sb.Append(indent).AppendLine("}");
    }

    // 인라인 파싱식으로 끝나는 스칼라는 전용 헬퍼가 없으므로 맵에 들어가지 않는다.
    private static Dictionary<INamedTypeSymbol, string> BuildNestedTokenMap(ImmutableArray<ParameterAnalysis> parameters)
    {
        // Roslyn 심볼은 참조 동일성이 보장되지 않아 전용 비교자가 필요 (같은 타입 다른 인스턴스 상황이나 nullable에서 문제 발생)
        var map = new Dictionary<INamedTypeSymbol, string>(SymbolEqualityComparer.Default);
        CollectNestedTokens(parameters, map);

        return map;
    }

    private static void CollectNestedTokens(
        ImmutableArray<ParameterAnalysis> parameters,
        Dictionary<INamedTypeSymbol, string> map)
    {
        foreach (var param in parameters)
        {
            if (param.Nested is { } nested && !map.ContainsKey(nested.Symbol))
            {
                map[nested.Symbol] = MakeToken(nested.Symbol.Name, map);
                CollectNestedTokens(nested.Parameters, map);
            }

            if (param.Collection is { ElementNested: { } elementNested }
                && !map.ContainsKey(elementNested.Symbol))
            {
                map[elementNested.Symbol] = MakeToken(elementNested.Symbol.Name, map);
                CollectNestedTokens(elementNested.Parameters, map);
            }

            if (param.Collection is { Kind: CollectionKind.FrozenDictionary } collection
                && collection.ValueNested is { } valueNested
                && !map.ContainsKey(valueNested.Symbol))
            {
                map[valueNested.Symbol] = MakeToken(valueNested.Symbol.Name, map);
                CollectNestedTokens(valueNested.Parameters, map);
            }

            if (param.Collection is { ElementKind: ScalarKind.Enum, ElementNested: null } enumCollection)
            {
                var enumType = (INamedTypeSymbol)TypeClassifier.UnwrapNullable(enumCollection.ElementType);
                if (!map.ContainsKey(enumType))
                {
                    map[enumType] = MakeToken(enumType.Name, map);
                }
            }
        }
    }

    private static string MakeToken(string baseName, Dictionary<INamedTypeSymbol, string> map)
    {
        return FormattableString.Invariant($"{map.Count + 1}_{baseName}");
    }

    private static string HelperName(string prefix, string ownerToken, string name)
    {
        if (ownerToken.Length == 0)
        {
            return $"{prefix}{name}";
        }

        return $"{prefix}{ownerToken}_{name}";
    }

    private static void EmitHelpers(
        StringBuilder sb,
        ImmutableArray<ParameterAnalysis> parameters,
        string indent,
        Dictionary<INamedTypeSymbol, string> nestedTokens)
    {
        var emittedHelperTypes = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        EmitHelpersRecursive(sb, parameters, emittedHelperTypes, indent, ownerToken: string.Empty, nestedTokens);
    }

    private static void EmitHelpersRecursive(
        StringBuilder sb,
        ImmutableArray<ParameterAnalysis> parameters,
        HashSet<INamedTypeSymbol> emittedHelperTypes,
        string indent,
        string ownerToken,
        Dictionary<INamedTypeSymbol, string> nestedTokens)
    {
        foreach (var param in parameters)
        {
            var effectiveKind = param.Collection is { } rangeCollection ? rangeCollection.ElementKind : param.Kind;
            var effectiveType = param.Collection is { } typeCollection ? typeCollection.ElementType : param.Type;

            if (param.Kind == ScalarKind.Enum)
            {
                sb.AppendLine();
                EmitEnumHelper(sb, param, indent, ownerToken);
            }

            if (param.Range is { ArgKind: RangeArgKind.Numeric })
            {
                sb.AppendLine();
                EmitNumericRangeHelper(sb, param, effectiveKind, indent, ownerToken);
            }
            else if (param.Range is { ArgKind: RangeArgKind.Typed })
            {
                sb.AppendLine();
                EmitTypedRangeHelper(sb, param, effectiveKind, effectiveType, indent, ownerToken);
            }

            if (param.RegexPattern is not null)
            {
                sb.AppendLine();
                EmitRegexHelper(sb, param, indent, ownerToken);
            }

            if (param.Collection is null &&
                param.Nested is null &&
                !param.IsIgnored &&
                param.IsNullable &&
                param.NullString is not null)
            {
                sb.AppendLine();
                EmitNullableScalarHelper(sb, param, indent, ownerToken);
            }

            if (param.Nested is { } nested && emittedHelperTypes.Add(nested.Symbol))
            {
                sb.AppendLine();
                EmitNestedHelper(sb, nested, indent, nestedTokens);
                EmitHelpersRecursive(sb, nested.Parameters, emittedHelperTypes, indent, nestedTokens[nested.Symbol], nestedTokens);
            }

            if (param.Collection is not null)
            {
                sb.AppendLine();

                EmitCollectionElementEnumHelper(sb, param, emittedHelperTypes, indent, nestedTokens);

                if (param.Collection.Kind == CollectionKind.ImmutableArray)
                {
                    EmitCollectionElementNestedHelpers(sb, param, emittedHelperTypes, indent, nestedTokens);
                    EmitArrayHelper(sb, param, indent, ownerToken, nestedTokens);
                }
                else if (param.Collection.Kind == CollectionKind.FrozenSet)
                {
                    EmitCollectionElementNestedHelpers(sb, param, emittedHelperTypes, indent, nestedTokens);
                    EmitSetHelper(sb, param, indent, ownerToken, nestedTokens);
                }
                else if (param.Collection.Kind == CollectionKind.FrozenDictionary)
                {
                    var valueNested = param.Collection.ValueNested!;
                    if (emittedHelperTypes.Add(valueNested.Symbol))
                    {
                        EmitNestedHelper(sb, valueNested, indent, nestedTokens);
                        sb.AppendLine();
                        EmitHelpersRecursive(sb, valueNested.Parameters, emittedHelperTypes, indent, nestedTokens[valueNested.Symbol], nestedTokens);
                    }

                    EmitDictHelper(sb, param, indent, ownerToken, nestedTokens);
                }
                else if (param.Collection.Kind == CollectionKind.SingleColumnImmutableArray)
                {
                    EmitSingleColumnArrayHelper(sb, param, indent, ownerToken, nestedTokens);
                }
                else if (param.Collection.Kind == CollectionKind.SingleColumnFrozenSet)
                {
                    EmitSingleColumnSetHelper(sb, param, indent, ownerToken, nestedTokens);
                }
            }
        }
    }
}
